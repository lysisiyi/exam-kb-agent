/// 知识库两个视图（图谱 / 大纲）与详情卡共用的**字号刻度**。
///
/// ## 为什么必须集中
///
/// 用户反馈「知识库图谱的字尺寸深浅不一」。查下来是同一屏里混了 **4 种**
/// 字号，而且**没有一个是按可读性定的** —— 全是各处的字面量：
///
/// | 位置 | 改前 | 改前来源 |
/// |---|---|---|
/// | 图谱节点名 | 12.5 | `knowledge_graph_view.dart` 里的字面量 |
/// | 工具栏百分比 | 11.5 | 同上 |
/// | 图例 | 11 | 同上 |
/// | 考频数字 | 10.5 | 同上 |
///
/// 更关键的是 12.5 **比全应用正文（`AppTypography.body` = 14）还小**。
/// 图谱节点是"要读的目录文字"，却成了整个应用里最小的正文。
///
/// ## 三档 + 一档，按**角色**分而不是按页面分
///
/// | 档 | 值 | 角色 |
/// |---|---|---|
/// | [heading] | 15 | 详情卡的标题（卡片自身的名字） |
/// | [title] | 14 | 图谱节点名 / 大纲行名 —— 与 `AppTypography.body` 同档 |
/// | [body] | 13 | 详情正文：定义、常见陷阱、考频字段值 |
/// | [secondary] | 12 | 计数、编号、面包屑、图例、提示 —— 与 `caption` 同档 |
///
/// 分档依据是**读者对它的关注度**，不是"越深越小"。
///
/// ## ⚠️ 层级不靠字号表达
///
/// 图谱里"章节"与"知识点"的层级差，靠**字重 + 颜色**表达
/// （见 `knowledge_node_style.dart`，那条原则已经先用在颜色上了）。
/// 若改用字号表达层级，同一张图里就会重新出现"大小不一" —— 也就是
/// 用户这次反馈的问题。**所以 [title] 只有一个值，不按层级分档。**
///
/// ## 颜色不在这里
///
/// 这里只管字号。文字颜色一律走 `nodeThemeOf()` / `kSecondaryInk`，
/// 因为颜色还有对比度硬约束（≥ 4.5:1）由测试守着，混在一起会失守。
library;

/// 知识库视图的字号刻度。
abstract final class KnowledgeSizes {
  const KnowledgeSizes._();

  /// 详情卡的标题。
  static const double heading = 15;

  /// 节点名 / 大纲行名 / 面板里的考点名。
  ///
  /// 与 `AppTypography.body`（14）同档：它是"要读的目录文字"，
  /// 不该比应用正文更小。
  static const double title = 14;

  /// 详情正文：定义、常见陷阱、考频字段值。
  static const double body = 13;

  /// 次要信息：计数、编号、面包屑、图例、操作提示。
  ///
  /// 与 `AppTypography.caption`（12）同档。**注意颜色**：12 号字在这个
  /// 项目里常常配 `ink3`，而 `ink3` 白底上只有 3.2:1（低于 AA）——
  /// 凡是"要读"的次要文字都要配 `kSecondaryInk`，见那个常量的注释。
  static const double secondary = 12;
}
