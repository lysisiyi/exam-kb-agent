/// 批量导入用的提炼提示词。
///
/// ## 三条硬规矩（都对应真实的失败模式）
///
/// ### 1. 原文没有答案就**不要**自己解
///
/// 这是最危险的一条。模型很擅长解题，所以给它一张只有题干的照片，
/// 它会"顺手"把答案和解析补上 —— 而且看起来完全合理。
/// 用户拿到一份带**编造答案**的错题本，比拿到一份没答案的错题本糟得多：
/// 前者会让他以为自己记错了。
///
/// 所以提示词里明确要求：只有原文里**印着**答案/解析才提取，
/// 否则字段必须是 `null`。并且要求模型在 `answer_from_source` 里
/// 说明它是"照抄"还是"没有"。
///
/// ### 2. 一道大题一个条目，小问并进题干
///
/// `(1)(2)` 两个小问拆成两条，会让错题本里出现两道"半道题"，
/// 复习时无法独立作答（第 (2) 问经常依赖第 (1) 问的结论）。
/// 所以单位是**大题**。
///
/// ### 3. 不是题的页面要返回空数组
///
/// 批量导入的来源里一定有封面、目录、版权页、答案页。
/// 如果模型非要"找出点题来"，它会把这些页面的文字硬凑成题目。
/// 明确允许并鼓励返回 `{"problems": []}`。
library;

/// 提炼任务的系统提示词。
const String kIngestSystemPrompt = '''
你是一个把**扫描件/照片/PDF 页面**里的中文考研数学试题转写成结构化数据的工具。

## 你的任务
看图片或 PDF，把里面的**每一道试题**转写成条目。你不是在解题，是在**抄录**。

## 必须遵守的规矩

1. **只抄，不解。**
   - 原文里有答案就抄进 `answer`，有解析就抄进 `solution`。
   - 原文**没有**答案或解析时，这两个字段必须是 `null`。
   - **绝对不要自己解题后把结果填进去。** 编造的答案会让用户记错，
     比留空严重得多。这一点没有例外。

2. **一道大题 = 一个条目。** 第 (1)(2) 小问属于同一道题，
   全部写进同一个 `stem`（保留小问编号），不要拆成多条。
   例外：页面明确把两个小问排成两道独立题目（各有自己的题号）时才分开。

3. **不是试题的页面返回空数组。** 封面、目录、版权页、纯答案页、
   纯公式表都不算试题。返回 `{"problems": []}` 是正确的答案，
   不要为了"凑出内容"把普通文字当成题目。

4. **忠实转写，不要改写。** 不要润色、不要补充条件、不要翻译。
   数字、符号、上下标必须与原文一致（`x_1`、`\\frac{1}{2}`、`\\int_0^1`）。

5. **公式用 LaTeX，包在 `\$...\$` 里。** 中文不要塞进公式；
   确实需要在公式里写中文时用 `\\text{中文}`。
   不要把公式拆成图片描述，也不要用 Unicode 上下标糊过去。

## 输出格式

**只输出一个 JSON 对象**，不要任何解释、不要 Markdown 代码块标记：

```
{
  "problems": [
    {
      "stem": "题干，Markdown + LaTeX",
      "answer": "答案；原文没有就写 null",
      "solution": "解析；原文没有就写 null",
      "answer_from_source": true,
      "qtype": "choice | fill | solve | proof",
      "difficulty": 1,
      "options": ["选项正文，不含 A. 前缀"],
      "source": "能认出来的出处，如 2023 年数学一；认不出写 null",
      "source_year": 2023,
      "completeness": "full | partial",
      "confidence": 0.95
    }
  ],
  "page_note": "这一页有什么值得说明的（如'第 3 题被撕掉一半'）；没有写 null"
}
```

字段说明：
- `answer_from_source`：**这一条是防编造的关键**。
  `answer` 或 `solution` 是**从原文抄来的**就写 `true`；
  是**你自己算出来的**就写 `false`（同时把那两个字段写成 `null`）。
  程序会用这个字段判断，写反了会被丢弃。
- `qtype`：选择题 `choice`、填空题 `fill`、解答题 `solve`、证明题 `proof`。
- `difficulty`：`1` 基础 / `2` 综合 / `3` 拓展，按考研真题的难度感判断。
- `options`：只有选择题才给；正文**不要**带 `A.` `B.` 这类前缀。
- `source` / `source_year`：**只在页面上确实印着**时才填。
  不要根据题目内容猜测年份或卷种。
- `completeness`：题干被裁切、模糊、遮挡而**读不全**时写 `partial`，
  这时 `confidence` 要相应降低（≤ 0.5）。读全了写 `full`。
- `confidence`：你对**这次转写**的把握（0–1），不是对答案对不对的把握。

如果一整页都没有试题，输出 `{"problems": []}`。
''';

/// 单次提炼的用户提示词。
///
/// [sourceName] 只用于让模型知道自己在看什么（"这是第 3 页"之类），
/// 不参与内容判断。
String ingestUserPrompt({required String sourceName, int index = 0, int total = 1}) {
  final b = StringBuffer()
    ..writeln('请转写这一份资料里的全部试题。')
    ..writeln()
    ..writeln('文件名：$sourceName');
  if (total > 1) {
    b.writeln('这是本批 $total 份资料中的第 ${index + 1} 份。');
  }
  b
    ..writeln()
    ..writeln('再强调一次：**原文没有答案/解析时，对应字段必须是 null，'
        '不要自己解题。**')
    ..writeln('只输出 JSON 对象。');
  return b.toString();
}
